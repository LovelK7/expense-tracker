package hr.ml.expensetracker.session

import android.content.Context
import android.util.Log
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException

sealed interface GoogleIdTokenResult {
    data class Success(val idToken: String) : GoogleIdTokenResult

    /** The user closed the account picker. */
    data object Cancelled : GoogleIdTokenResult

    /** No Google account on the device (or none usable). */
    data object NoAccount : GoogleIdTokenResult

    data class Failure(val cause: Throwable) : GoogleIdTokenResult
}

/**
 * "Sign in with Google" through AndroidX Credential Manager. [webClientId] is the OAuth web client
 * of the Firebase project (`default_web_client_id`, generated by the google-services plugin);
 * the returned ID token is exchanged for a Firebase credential.
 */
class GoogleSignIn(private val webClientId: String) {
    /** [activityContext] must be an Activity: Credential Manager shows its picker on top of it. */
    suspend fun requestIdToken(activityContext: Context): GoogleIdTokenResult {
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(GetSignInWithGoogleOption.Builder(webClientId).build())
            .build()
        return try {
            val credential = CredentialManager.create(activityContext)
                .getCredential(activityContext, request).credential
            if (credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                GoogleIdTokenResult.Success(GoogleIdTokenCredential.createFrom(credential.data).idToken)
            } else {
                GoogleIdTokenResult.Failure(IllegalStateException("unexpected credential ${credential.type}"))
            }
        } catch (e: GetCredentialCancellationException) {
            GoogleIdTokenResult.Cancelled
        } catch (e: NoCredentialException) {
            Log.w(TAG, "no Google account available", e)
            GoogleIdTokenResult.NoAccount
        } catch (e: GetCredentialException) {
            Log.w(TAG, "getCredential failed", e)
            GoogleIdTokenResult.Failure(e)
        } catch (e: GoogleIdTokenParsingException) {
            Log.w(TAG, "bad Google ID token", e)
            GoogleIdTokenResult.Failure(e)
        }
    }

    private companion object {
        const val TAG = "GoogleSignIn"
    }
}
